//  "пакет_3"
// )

// Обязательность использования импортируемых пакетов
// Иногда бывает так, что всё таки нужно, чтобы пакет был объявлен, но не был использован,
// компилятор Go не позволяет скомпилировать программу, если имеется неиспользуемый пакет.
// В этом случае можно явно дать понять, что пакет временно не используется
// с помощью подчеркивания перед пакетом

// import _ "Название_пакета_временно_неиспользующийся"
//
//
import (
	. "fmt"
	. "math"
	_ "reflect" // Пакет временно не используется
)
