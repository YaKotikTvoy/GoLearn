package main // пакет является отправной точкой для создания программы на Go
// Они содержат функционал, который может быть переиспользуемым
// пакеты бывают двух типов:
// * исполняемые (executable)
// * библиотеки (reusable)

// Для создания исполняемых пакетов пакет должен:
// 1) называться "main"
// 2) содержать функцию "main"

// Для подключения уже известной функциональности используется:
// import "Название_пакета"

// Нередко программы подключают сразу несколько пакетов для этого используют такой синтаксис:
// import (
//  "Название_первого_пакета"
//  "Название_второго_пакета"
//  "Название_третьего_пакета"
//  "Пакет_n"
// )

// Также можно подключать пакеты и так:
// import "Название_первого_пакета"
// import "Название_второго_пакета"
// import "Название_третьего_пакета"
// import "Пакет_n"
// То есть предварять каждый подключаемы пакет ключевым словом "import"

// import (
//  "fmt"
//  "math"
// )

// dot import - позволяет импортировать содержимое пакета так, что нет необходимости
// dot import - аналог вставки пакета как в C# using static System.Console
// обращаться к функционалу пакета через "."
// имеет следущий синтаксис
// import . "Name_package1"
// import . "Name_package1"
// import . "Name_package1"

// import (
//  "пакет_1"
