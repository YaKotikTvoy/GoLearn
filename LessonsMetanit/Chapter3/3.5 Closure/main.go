func outer() func() {
	var n int = 5 //Некоторая переменная - лексическое окружение функции inner

	var inner func() = func() { // Вложенная функция, которая имеет доступ к внутренностям outer
		// действия с переменой n, которая будет запомнена функцией inner
		n++
		fmt.Println(n)
	}
	// лексическому окружению
	fmt.Println(n)
	return inner
}

func multiple(n int) func(int) int {
	return func(m int) int { return n * m }
}
